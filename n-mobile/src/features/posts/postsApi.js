import { supabase } from '../../lib/supabase.js'

// Posts history + drafts (table posts, private bucket 'posts'; see migrations 002, 004 and 007).
// Files live under <user_id>/ (required by the storage policies from 002).
// Status shown in the app: 'draft' | 'exported' (downloaded/shared only) | 'posted' (published to Instagram).
// Rows saved before migration 008 were marked 'posted' on every export, so a 'posted'/empty
// status without any Instagram id/link is treated as 'exported'.
export const postStatus = (p) => {
  if (p.status === 'draft' || p.status === 'exported') return p.status
  return p.ig_media_id || p.ig_permalink ? 'posted' : 'exported'
}
const up = async (path, blob) => { const r = await supabase.storage.from('posts').upload(path, blob, { contentType: blob.type || 'image/jpeg', upsert: true }); if (r.error) throw r.error }
const ext = (b) => (b.type === 'image/png' ? 'png' : b.type === 'image/webp' ? 'webp' : 'jpg')
const ver = () => Date.now().toString(36)
// Storage paths a post row can reference
const FILE_COLS = ['image_path', 'photo_path', 'photo2_path', 'photo_orig_path']
const filesOf = (p) => FILE_COLS.map((c) => p[c]).filter(Boolean)

/* Creates or updates (upsert) the row `id` (uuid generated by the client, so retries/autosaves
   never create duplicates and file names are known before the row exists).
   files.preview: rendered post image (always new).
   files.photo / files.photo2 / files.photoOrig (uploaded original while the background is removed): Blob = upload a new version; null = remove; undefined = keep.
   prev: the paths currently stored on the row ({ image_path, photo_path, photo2_path }).
   Every changed file gets a new versioned name (no stale CDN copies); replaced files are
   removed only after the row update succeeded. Returns the stored paths. */
export async function savePost(uid, id, meta, { preview, photo, photo2, photoOrig } = {}, prev = {}) {
  const row = { id, user_id: uid, ...meta, updated_at: new Date().toISOString() }
  const kind = meta.status === 'draft' ? 'draft' : 'post'
  const paths = { image_path: prev.image_path || null, photo_path: prev.photo_path || null, photo2_path: prev.photo2_path || null, photo_orig_path: prev.photo_orig_path || null }
  const stale = []
  const put = async (col, blob, name) => {
    if (blob === undefined) return
    if (paths[col]) stale.push(paths[col])
    if (blob === null) { paths[col] = null; return }
    const p = `${uid}/${id}-${name}-${ver()}.${ext(blob)}`; await up(p, blob); paths[col] = p
  }
  await Promise.all([put('image_path', preview, kind), put('photo_path', photo, 'photo'), put('photo2_path', photo2, 'photo2'), put('photo_orig_path', photoOrig, 'orig')])
  const { error } = await supabase.from('posts').upsert({ ...row, ...paths })
  if (error) { const fresh = Object.values(paths).filter((p) => p && !Object.values(prev).includes(p)); if (fresh.length) supabase.storage.from('posts').remove(fresh).catch(() => {}); throw error }
  if (stale.length) supabase.storage.from('posts').remove(stale).catch(() => {})
  return paths
}
export async function listPosts() {
  const { data, error } = await supabase.from('posts').select('*').order('updated_at', { ascending: false }).limit(60)
  if (error) throw error
  const paths = data.flatMap(filesOf)
  const urls = paths.length ? (await supabase.storage.from('posts').createSignedUrls(paths, 3600)).data || [] : []
  const map = Object.fromEntries(urls.filter((u) => u.signedUrl).map((u) => [u.path, u.signedUrl]))
  return data.map((p) => ({ ...p, url: map[p.image_path], photoUrl: map[p.photo_path], photo2Url: map[p.photo2_path], photoOrigUrl: map[p.photo_orig_path] }))
}
export async function deletePost(p) {
  const files = filesOf(p)
  const { error } = await supabase.from('posts').delete().eq('id', p.id)
  if (error) throw error
  if (files.length) await supabase.storage.from('posts').remove(files)
}
